"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import GaussianWorldViewer from "@/components/gaussian-world-viewer";

const API = process.env.NEXT_PUBLIC_API_URL || "";

export default function WorldPage() {
  const [src, setSrc] = useState("");
  const [manualSrc, setManualSrc] = useState("");
  const [active, setActive] = useState("");
  const [message, setMessage] = useState("");
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    const videoId = new URLSearchParams(window.location.search).get("videoId");
    if (!videoId) return;
    if (!API) {
      setMessage("The 3D world API is not connected to this public preview yet.");
      return;
    }
    let cancelled = false;
    setLoading(true);
    fetch(`${API}/api/v1/worlds/${encodeURIComponent(videoId)}/asset`, { cache: "no-store" })
      .then(async response => {
        const data = await response.json();
        if (!response.ok) throw new Error(data.detail || "This destination is not ready yet.");
        return data as { asset_url: string };
      })
      .then(data => {
        if (!cancelled) { setSrc(data.asset_url); setActive(data.asset_url); setMessage("Your reconstructed destination is ready."); }
      })
      .catch(error => {
        if (!cancelled) setMessage(error instanceof Error ? error.message : "Could not load this destination.");
      })
      .finally(() => { if (!cancelled) setLoading(false); });
    return () => { cancelled = true; };
  }, []);

  return <main className="min-h-screen bg-[#07111f] px-5 py-8 text-white">
    <div className="mx-auto max-w-7xl">
      <Link href="/" className="text-sm text-[#54d6c8]">← Travel Universe</Link>
      <p className="mt-10 text-xs font-bold tracking-[.3em] text-[#54d6c8]">ENTER A WORLD</p>
      <h1 className="mt-3 text-4xl font-semibold">Explore a reconstructed place.</h1>
      <p className="mt-4 max-w-3xl leading-7 text-white/60">Open a world created from your uploaded travel footage, or load a supported Gaussian Splat scene URL.</p>
      <form className="mt-7 flex flex-col gap-3 sm:flex-row" onSubmit={e => { e.preventDefault(); setActive(manualSrc.trim()); setMessage(""); }}>
        <input aria-label="3D scene URL" value={manualSrc} onChange={e => setManualSrc(e.target.value)} placeholder="Paste a .spz, .ply, or .splat scene URL" className="min-w-0 flex-1 rounded-full border border-white/15 bg-white/[.06] px-5 py-3 text-sm outline-none focus:border-[#54d6c8]" />
        <button type="submit" disabled={!manualSrc.trim()} className="rounded-full bg-[#54d6c8] px-7 py-3 font-semibold text-[#07111f] disabled:opacity-40">Load world</button>
      </form>
      {(loading || message) && <p role="status" className="mt-4 text-sm text-white/65">{loading ? "Finding your published 3D destination…" : message}</p>}
      <div className="mt-7">
        {active ? <GaussianWorldViewer key={active} src={active} /> : <div className="flex min-h-[65vh] items-center justify-center rounded-3xl border border-dashed border-white/15 bg-white/[.025] p-8 text-center"><div><p className="text-xl font-semibold">Your 3D destination will appear here</p><p className="mt-3 text-sm text-white/50">Complete a reconstruction or paste a supported scene URL to enter</p></div></div>}
      </div>
      <p className="mt-5 text-xs leading-6 text-white/35">Scene links are short-lived when generated by the platform. Manually supplied scene files must be hosted with browser-accessible CORS headers.</p>
    </div>
  </main>;
}
